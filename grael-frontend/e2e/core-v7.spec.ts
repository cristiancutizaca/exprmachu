import { test, expect } from '@playwright/test'

test('login real, drawer overlay y logout', async ({ page }) => {
  await page.goto('/login')
  await page.waitForLoadState('networkidle')
  await expect(page.getByRole('button', { name: 'Ingresar' })).toBeEnabled()
  await page.getByPlaceholder('usuario@grael').fill(process.env.GRAEL_E2E_USER || 'jesus.cutisaca')
  await page.getByPlaceholder('••••••••').fill(process.env.GRAEL_E2E_PASSWORD || 'admin123')
  await page.getByRole('button', { name: 'Ingresar' }).click()
  await expect(page).toHaveURL(/\/recepcion$/)
  await expect(page.getByText('Registro de la Nueva Recepcion de Carga')).toBeVisible()

  const drawer = page.getByRole('complementary', { name: 'Menú Operaciones' })
  await expect(drawer).toHaveCSS('transform', /matrix\(1, 0, 0, 1, -/)
  await page.getByRole('button', { name: /Menú|menu/i }).first().click()
  await expect(drawer).toHaveCSS('transform', /matrix\(1, 0, 0, 1, 0, 0\)/)
  await page.keyboard.press('Escape')
  await expect(drawer).toHaveCSS('transform', /matrix\(1, 0, 0, 1, -/)

  await page.getByText('JESUS SAMUEL').click()
  const logout = page.getByText(/Cerrar sesión|Salir|Logout/i).first()
  await logout.click()
  await expect(page).toHaveURL(/\/login$/)
})

