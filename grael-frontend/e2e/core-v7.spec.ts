test('búsqueda QR real y acciones de QR/impresión', async ({ page }) => {
  await page.goto('/login')
  await page.getByPlaceholder('usuario@grael').fill(process.env.GRAEL_E2E_USER || 'jesus.cutisaca')
  await page.getByPlaceholder('••••••••').fill(process.env.GRAEL_E2E_PASSWORD || 'admin123')
  await page.getByRole('button', { name: 'Ingresar' }).click()
  await expect(page).toHaveURL(/\/recepcion$/)
  await page.goto('/busqueda-qr')
  await page.getByPlaceholder('301-0631143 o escanear QR...').fill(process.env.GRAEL_E2E_TICKET || '301-0631201')
  await page.getByRole('button', { name: 'Buscar' }).click()
  await expect(page.getByText('Ticket encontrado')).toBeVisible({ timeout: 15_000 })
  const qrPopup = page.waitForEvent('popup')
  const qrResponse = page.waitForResponse(response => response.url().includes('/tickets/') && response.url().endsWith('/qr') && response.request().method() === 'GET')
  await page.getByRole('button', { name: 'Ver QR' }).click()
  const [qrPage, response] = await Promise.all([qrPopup, qrResponse])
  expect(response.status()).toBe(200)
  await expect(qrPage).toBeTruthy()
  await qrPage.close()
})


test('Caja Diaria real: apertura, movimiento y cierre', async ({ page }) => {
  await page.goto('/login')
  await page.getByPlaceholder('usuario@grael').fill(process.env.GRAEL_E2E_CASH_USER || 'maria.garcia')
  await page.getByPlaceholder('••••••••').fill(process.env.GRAEL_E2E_CASH_PASSWORD || 'caj123')
  await page.getByRole('button', { name: 'Ingresar' }).click()
  await expect(page).toHaveURL(/\/recepcion$/)
  await page.goto('/caja-diaria')
  await expect(page.getByRole('heading', { name: 'Caja Diaria' })).toBeVisible()
  await page.getByRole('button', { name: 'Abrir caja' }).last().click()
  await expect(page.getByRole('heading', { name: 'Abrir caja' })).toBeVisible()
  await page.getByLabel('Saldo inicial').fill('50')
  await page.getByLabel('Observación de apertura').fill('E2E Caja V9')
  await page.getByRole('button', { name: 'Abrir caja' }).last().click()
  await expect(page.getByText('Caja abierta')).toBeVisible({ timeout: 10_000 })
  await page.getByRole('button', { name: 'Movimiento' }).click()
  await page.getByLabel('Monto').fill('20')
  await page.getByLabel('Motivo / concepto').fill('E2E ingreso efectivo')
  await page.getByRole('button', { name: 'Guardar' }).click()
  await expect(page.getByText('Movimiento registrado')).toBeVisible({ timeout: 10_000 })
  await page.getByRole('button', { name: 'Cierre de caja' }).click()
  await page.getByLabel('Efectivo contado').fill('70')
  await page.getByRole('button', { name: 'Cerrar caja' }).click()
  await expect(page.getByText('Sin caja abierta')).toBeVisible({ timeout: 10_000 })
})
